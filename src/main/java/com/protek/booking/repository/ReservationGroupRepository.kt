package com.protek.booking.repository

import com.protek.booking.db.DataAccessException
import com.protek.booking.db.Db
import com.protek.booking.domain.ReservationGroup
import jakarta.enterprise.context.ApplicationScoped
import jakarta.inject.Inject
import java.math.BigDecimal
import java.sql.Connection
import java.sql.ResultSet
import java.sql.SQLException
import java.sql.Savepoint
import java.time.Instant
import java.util.Optional
import java.util.UUID

/** Every reservation belongs to a group, even a single seat — "a group of one" —
 * so a single seat and an N-seat block share one all-or-nothing confirmation concept. */
@ApplicationScoped
class ReservationGroupRepository {

    @Inject
    lateinit var db: Db

    /**
     * Inserts the group, letting the database mint its `booking_code`.
     *
     * **Why the retry, and why a savepoint.** The code is generated by a column DEFAULT
     * and is unique per tenant, so two bookings can in principle draw the same eight characters
     * and the second insert fails on `idx_reservation_group_booking_code`. Nothing
     * pre-checks the code — the unique index is the arbiter, in the same spirit as the EXCLUDE
     * constraint — so recovering means re-issuing the insert, which re-evaluates the
     * volatile default and draws a fresh code.
     *
     * Postgres aborts the whole transaction on a failed statement, so the retry cannot simply
     * be a loop: without a savepoint the second attempt fails with "current transaction is
     * aborted" and the customer loses the booking to a coin flip. `ROLLBACK TO SAVEPOINT`
     * unwinds exactly the failed insert and leaves everything this transaction has already done
     * — the session lock, the hold — intact.
     *
     * It costs one extra round trip per booking, and it is worth stating that plainly: the
     * savepoint has to be taken *before* the insert that might fail, so it cannot be made
     * conditional on a collision that has not happened yet. The alternative is a booking that
     * fails outright on a coincidence, on a path that already spends round trips on
     * `FOR UPDATE` for the same reason — correctness a customer can feel.
     */
    fun insert(c: Connection, tenantId: UUID?, resourcePoolId: UUID?,
               customerId: UUID?, requestedUnitCount: Int): ReservationGroup {
        val sql = ("INSERT INTO reservation_group (tenant_id, resource_pool_id, customer_id, "
                + "requested_unit_count) VALUES (?, ?, ?, ?) RETURNING " + COLUMNS)
        var attempt = 1
        while (true) {
            val mark = savepoint(c)
            try {
                val group = db.queryOne(c, sql, ::map,
                    tenantId, resourcePoolId, customerId, requestedUnitCount).orElseThrow()
                release(c, mark)
                return group
            } catch (e: DataAccessException) {
                if (attempt >= BOOKING_CODE_ATTEMPTS || !isBookingCodeCollision(e)) {
                    throw e
                }
                rollbackTo(c, mark)
            }
            attempt++
        }
    }

    private fun isBookingCodeCollision(e: DataAccessException): Boolean =
        e.isUniqueViolation() && e.message != null && e.message!!.contains(BOOKING_CODE_INDEX)

    private fun savepoint(c: Connection): Savepoint {
        try {
            return c.setSavepoint("booking_code")
        } catch (e: SQLException) {
            throw DataAccessException("<savepoint booking_code>", e)
        }
    }

    private fun rollbackTo(c: Connection, mark: Savepoint) {
        try {
            c.rollback(mark)
        } catch (e: SQLException) {
            throw DataAccessException("<rollback to booking_code>", e)
        }
    }

    private fun release(c: Connection, mark: Savepoint) {
        try {
            c.releaseSavepoint(mark)
        } catch (ignored: SQLException) {
            // Deliberately swallowed: an unreleased savepoint costs a little memory until the
            // transaction ends and nothing else. Throwing here would lose an insert that has
            // already succeeded, which is a far worse outcome than the leak it would report.
        }
    }

    fun findById(c: Connection, tenantId: UUID?, reservationGroupId: UUID?): Optional<ReservationGroup> =
        db.queryOne(c,
            "SELECT " + COLUMNS + " FROM reservation_group WHERE tenant_id = ? AND reservation_group_id = ?",
            ::map, tenantId, reservationGroupId)

    /**
     * The counter's "I am calling about K7M2QPRT" lookup.
     *
     * An exact match on an uppercase code rather than an `ILIKE` or a trigram search:
     * the unique index is on the stored value, and anything case-insensitive in SQL would not
     * use it. Callers normalise what the human typed instead — see
     * `BookingService.findGroupByBookingCode`, the same split
     * `AdmissionService.normalise` uses for admission tokens.
     */
    fun findByBookingCode(c: Connection, tenantId: UUID?, bookingCode: String?): Optional<ReservationGroup> =
        db.queryOne(c,
            "SELECT " + COLUMNS + " FROM reservation_group WHERE tenant_id = ? AND booking_code = ?",
            ::map, tenantId, bookingCode)

    /**
     * One row per booking for the order-history page, assembled in SQL rather than by
     * re-reading each group.
     *
     * **Why not reuse `BookingService.getGroupDetail` in a loop.** That method is
     * four queries per group — hall, seats, showing, and a seat lookup per line — so a customer
     * with twenty bookings would cost eighty round trips to render a list that shows none of the
     * per-seat detail. This is one query with the aggregate the page actually displays.
     *
     * Every join is a LEFT JOIN on purpose. A `failed` group has no reservation rows at
     * all (the whole group is rolled back when one seat is taken first), and it is exactly
     * the booking a customer is most likely to come looking for an explanation of — an inner
     * join would drop it from the history silently.
     *
     * Grouping by the showing's columns is safe because a group is held against one showing:
     * `BookingService.holdInternal` takes a single `sessionId` for the whole
     * request, so there is no group whose seats span two of them.
     */
    fun findHistoryForCustomer(c: Connection, tenantId: UUID?, customerId: UUID?, limit: Int): List<HistoryEntry> =
        db.query(c,
            "SELECT g.reservation_group_id, g.booking_code, g.status, g.created_at, " +
                    "p.name AS hall_name, s.label AS showing_label, s.starts_at AS showing_starts_at, " +
                    "count(r.reservation_id) AS seat_count, " +
                    "coalesce(sum(r.price_amount) FILTER (WHERE r.status <> 'cancelled'), 0) AS total_amount, " +
                    // A scalar subquery rather than a fourth LEFT JOIN, and that is a
                    // correctness point rather than a style one: a group with two payment
                    // rows (a first charge that expired, then a second that settled) would
                    // duplicate every reservation row under the join, and count() and sum()
                    // above would both silently double. The page orders this list by when a
                    // customer paid, so the column had to be added without disturbing the
                    // two aggregates that were already right.
                    "(SELECT max(pay.paid_at) FROM payment pay " +
                    " WHERE pay.tenant_id = g.tenant_id " +
                    " AND pay.reservation_group_id = g.reservation_group_id " +
                    " AND pay.status = 'paid') AS paid_at " +
                    "FROM reservation_group g " +
                    "JOIN resource_pool p ON p.tenant_id = g.tenant_id " +
                    "  AND p.resource_pool_id = g.resource_pool_id " +
                    "LEFT JOIN reservation r ON r.tenant_id = g.tenant_id " +
                    "  AND r.reservation_group_id = g.reservation_group_id " +
                    "LEFT JOIN resource_pool_session s ON s.tenant_id = r.tenant_id " +
                    "  AND s.resource_pool_session_id = r.resource_pool_session_id " +
                    "WHERE g.tenant_id = ? AND g.customer_id = ? " +
                    "GROUP BY g.reservation_group_id, g.booking_code, g.status, g.created_at, " +
                    "  p.name, s.label, s.starts_at " +
                    // "Most recently paid first". NULLS LAST is what keeps an unpaid
                    // booking — a live hold on the payment page — from sorting above every
                    // settled one, which is what a bare DESC does in PostgreSQL, where NULL
                    // sorts highest by default.
                    "ORDER BY paid_at DESC NULLS LAST, g.created_at DESC " +
                    "LIMIT ?",
            ::mapHistory, tenantId, customerId, limit)

    /**
     * One line of order history.
     *
     * A `@JvmRecord`, as the nested Java record was, so the template and the Java tests keep
     * `bookingCode()`, `hasShowing()` and the rest.
     *
     * @param showingLabel     null for a `failed` group, which never got as far as a
     *                         reservation row to read a showing from.
     * @param totalAmount      what is still owed or was paid — cancelled seats are excluded, so
     *                         a partly-cancelled booking does not keep quoting its original
     *                         total back at the customer.
     * @param paidAt           when the last successful payment settled, or null for a booking
     *                         that has not been paid — a live hold, a counter sale settled in
     *                         cash, or a group that failed before it had an amount.
     */
    @JvmRecord
    data class HistoryEntry(val reservationGroupId: UUID?, val bookingCode: String?, val status: String?,
                            val createdAt: Instant?, val hallName: String?, val showingLabel: String?,
                            val showingStartsAt: Instant?, val seatCount: Int, val totalAmount: BigDecimal?,
                            val paidAt: Instant?) {

        /** Read by the template, which has no `null` handling of its own worth the name —
         * Qute expressions are validated at build time and the simpler they stay, the less there
         * is to get wrong in a file the compiler does not check. */
        fun hasShowing(): Boolean = showingLabel != null

        fun isPaid(): Boolean = paidAt != null

        /**
         * Whether this order is still something the customer can act on — the split between
         * the orders page's two sections.
         *
         * Two conditions, and the second is the one that is easy to leave out: the booking
         * must not be in a terminal state, *and* the showing must not have happened yet.
         * A confirmed booking for last Tuesday is not an active order; it is history, and
         * leaving it at the top of the page pushes the ticket somebody needs tonight below it.
         *
         * A group with no showing at all — `failed`, which never got as far as a
         * reservation row — is history by the same test, which is right: it is the thing a
         * customer comes here to ask about, and it is over.
         *
         * `now` is nullable as the Java's was: a terminal booking answers false
         * without ever reading it.
         */
        fun isActive(now: Instant?): Boolean {
            if ("pending" != status && "confirmed" != status) {
                return false
            }
            return showingStartsAt != null && showingStartsAt.isAfter(now)
        }
    }

    fun markConfirmed(c: Connection, tenantId: UUID?, reservationGroupId: UUID?): Int =
        db.execute(c,
            "UPDATE reservation_group SET status = 'confirmed', confirmed_at = now() " +
                    "WHERE tenant_id = ? AND reservation_group_id = ?",
            tenantId, reservationGroupId)

    fun markFailed(c: Connection, tenantId: UUID?, reservationGroupId: UUID?, failedResourceUnitId: UUID?): Int =
        db.execute(c,
            "UPDATE reservation_group SET status = 'failed', failed_resource_unit_id = ? " +
                    "WHERE tenant_id = ? AND reservation_group_id = ?",
            failedResourceUnitId, tenantId, reservationGroupId)

    fun markCancelled(c: Connection, tenantId: UUID?, reservationGroupId: UUID?): Int =
        db.execute(c,
            "UPDATE reservation_group SET status = 'cancelled' WHERE tenant_id = ? AND reservation_group_id = ?",
            tenantId, reservationGroupId)

    private fun map(rs: ResultSet): ReservationGroup {
        val confirmedAt = rs.getTimestamp("confirmed_at")
        return ReservationGroup(
            rs.getObject("reservation_group_id", UUID::class.java),
            rs.getString("booking_code"),
            rs.getObject("tenant_id", UUID::class.java),
            rs.getObject("resource_pool_id", UUID::class.java),
            rs.getObject("customer_id", UUID::class.java),
            rs.getInt("requested_unit_count"),
            rs.getString("status"),
            rs.getObject("failed_resource_unit_id", UUID::class.java),
            rs.getTimestamp("created_at").toInstant(),
            confirmedAt?.toInstant(),
        )
    }

    private fun mapHistory(rs: ResultSet): HistoryEntry {
        val startsAt = rs.getTimestamp("showing_starts_at")
        val paidAt = rs.getTimestamp("paid_at")
        return HistoryEntry(
            rs.getObject("reservation_group_id", UUID::class.java),
            rs.getString("booking_code"),
            rs.getString("status"),
            rs.getTimestamp("created_at").toInstant(),
            rs.getString("hall_name"),
            rs.getString("showing_label"),
            startsAt?.toInstant(),
            rs.getInt("seat_count"),
            rs.getBigDecimal("total_amount"),
            paidAt?.toInstant(),
        )
    }

    private companion object {
        const val COLUMNS =
            "reservation_group_id, booking_code, tenant_id, resource_pool_id, customer_id, " +
                    "requested_unit_count, status, failed_resource_unit_id, created_at, confirmed_at"

        /** The unique index on `(tenant_id, booking_code)`. Named here because a
         * SQLSTATE of 23505 says only "some unique index refused this row" — retrying on that alone
         * would silently paper over, say, a duplicate idempotency key, which is a violation the
         * caller must see rather than have re-attempted underneath it. */
        const val BOOKING_CODE_INDEX = "idx_reservation_group_booking_code"

        /** Three draws from 27^8 codes. The second is already a coincidence worth about one booking
         * in 2.8 million; a third failing means the generator is broken, not unlucky, and looping
         * further would turn that into a hung request instead of an error somebody reads. */
        const val BOOKING_CODE_ATTEMPTS = 3
    }
}
