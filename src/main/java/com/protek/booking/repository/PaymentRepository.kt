package com.protek.booking.repository

import com.protek.booking.db.DataAccessException
import com.protek.booking.db.Db
import com.protek.booking.domain.Payment
import jakarta.enterprise.context.ApplicationScoped
import jakarta.inject.Inject
import java.math.BigDecimal
import java.sql.Connection
import java.sql.ResultSet
import java.time.Instant
import java.time.LocalDate
import java.util.Optional
import java.util.UUID

/** Tenant-scoped and under RLS since V1. */
@ApplicationScoped
class PaymentRepository {

    @Inject
    lateinit var db: Db

    fun insertPending(c: Connection, tenantId: UUID?, reservationGroupId: UUID?,
                      amount: BigDecimal?, currency: String?, merchantId: String?,
                      triggerPoint: String?, partnerReferenceNo: String?, expiresAt: Instant?): Payment =
        // qris_terminal_id is deliberately not written here: BI-SNAP has a real terminalId but
        // the charge request does not send one, so leaving it NULL says that truthfully.
        db.queryOne(c,
            "INSERT INTO payment (tenant_id, reservation_group_id, amount, currency, " +
                    "qris_merchant_id, trigger_point, qris_partner_reference_no, expires_at, " +
                    "payment_channel) " +
                    "VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'qris') RETURNING " + COLUMNS,
            ::map, tenantId, reservationGroupId, amount, currency, merchantId,
            triggerPoint, partnerReferenceNo, expiresAt
        ).orElseThrow()

    /** A cash settlement: recorded already-paid, because the cash path is money taken at
     * the counter, not a charge awaiting confirmation. The
     * `cash_payments_are_never_pending` CHECK enforces that shape. */
    fun insertCashPaid(c: Connection, tenantId: UUID?, reservationGroupId: UUID?,
                       amount: BigDecimal?, currency: String?, merchantId: String?,
                       partnerReferenceNo: String?, settledByActor: String?): Payment =
        db.queryOne(c,
            "INSERT INTO payment (tenant_id, reservation_group_id, amount, currency, " +
                    "qris_merchant_id, trigger_point, qris_partner_reference_no, expires_at, " +
                    "status, paid_at, payment_channel, settled_by_actor) " +
                    "VALUES (?, ?, ?, ?, ?, 'counter', ?, now(), 'paid', now(), 'cash', ?) " +
                    "RETURNING " + COLUMNS,
            ::map, tenantId, reservationGroupId, amount, currency, merchantId,
            partnerReferenceNo, settledByActor
        ).orElseThrow()

    fun findById(c: Connection, tenantId: UUID?, paymentId: UUID?): Optional<Payment> =
        db.queryOne(c, "SELECT " + COLUMNS + " FROM payment WHERE tenant_id = ? AND payment_id = ?",
            ::map, tenantId, paymentId)

    /**
     * Resolves a payment from the `order_id` Midtrans echoes back, **without** a
     * tenant filter, and locks the row.
     *
     * No tenant filter because a webhook arrives with no identity and no tenant context —
     * Midtrans knows our order id, not our tenancy model — so the tenant has to be
     * *derived* from the row rather than supplied alongside it. That is safe here
     * specifically because `qris_partner_reference_no` is UNIQUE across the table and
     * generated by us as a random value: the caller cannot steer this lookup toward another
     * tenant's row, only present an id that either exists or does not. This is the one
     * deliberate exception to every other query's tenant scoping.
     *
     * Not tenant-filtered is **not** the same as context-free. This once ran on a
     * connection with no RLS context at all, which under FORCE ROW LEVEL SECURITY returns zero
     * rows rather than every row — see [com.protek.booking.payment.PaymentService.applyNotification]
     * for the settlement outage that caused. The caller must establish the owning tenant's
     * context first; the missing `tenant_id = ?` here only means it need not know it up
     * front from the request.
     *
     * `FOR UPDATE` is what makes duplicate webhook delivery safe: Midtrans retries,
     * and two concurrent deliveries for the same order would otherwise both read
     * `pending` and both apply the transition. The lock serialises them so the second
     * sees the first's committed result.
     */
    fun findByOrderIdForUpdate(c: Connection, partnerReferenceNo: String?): Optional<Payment> =
        db.queryOne(c,
            "SELECT " + COLUMNS + " FROM payment WHERE qris_partner_reference_no = ? FOR UPDATE",
            ::map, partnerReferenceNo)

    /**
     * Whether this connection's tenant context can see the given order id — the probe behind
     * `PaymentService`'s tenant scan.
     *
     * Deliberately not `FOR UPDATE`: the scan asks the question once per tenant, and
     * locking a row just to discover it exists would hold write locks across tenants that do not
     * own it. The real locked read happens afterwards, inside the transaction that mutates.
     */
    fun existsByOrderId(c: Connection, partnerReferenceNo: String?): Boolean =
        db.queryOne(c,
            "SELECT 1 FROM payment WHERE qris_partner_reference_no = ?",
            { _ -> true }, partnerReferenceNo).isPresent

    fun findByReservationGroup(c: Connection, tenantId: UUID?, reservationGroupId: UUID?): List<Payment> =
        db.query(c,
            "SELECT " + COLUMNS + " FROM payment WHERE tenant_id = ? AND reservation_group_id = ? " +
                    "ORDER BY created_at DESC",
            ::map, tenantId, reservationGroupId)

    /** Locks every payment of these orders, in the caller's (sorted) order, so two lockers of the
     * same orders cannot take them crosswise. */
    fun lockForGroups(c: Connection, tenantId: UUID?, reservationGroupIds: List<UUID>) {
        for (groupId in reservationGroupIds) {
            db.query(c, "SELECT payment_id FROM payment WHERE tenant_id = ? AND reservation_group_id = ? " +
                    "ORDER BY payment_id FOR UPDATE", { rs -> rs.getObject(1) }, tenantId, groupId)
        }
    }

    /** Records the QR payload and Midtrans's transaction id once the charge call returns. */
    fun attachChargeResult(c: Connection, tenantId: UUID?, paymentId: UUID?,
                           qrisContent: String?, qrisReferenceNo: String?): Int =
        db.execute(c,
            "UPDATE payment SET qris_content = ?, qris_reference_no = ? " +
                    "WHERE tenant_id = ? AND payment_id = ?",
            qrisContent, qrisReferenceNo, tenantId, paymentId)

    /**
     * Settles a payment. Guarded on `status = 'pending'` so a replayed webhook, or a
     * reconciliation run racing a live webhook, cannot re-settle an already-settled payment
     * (and cannot resurrect one that expired). The return value is how the caller learns
     * whether it was the one that actually applied the transition.
     */
    fun markPaid(c: Connection, partnerReferenceNo: String?, midtransTransactionId: String?,
                 settledByActor: String?, signatureVerified: Boolean, rawPayload: String?): Int =
        db.execute(c,
            "UPDATE payment SET status = 'paid', paid_at = now(), qris_reference_no = ?, " +
                    "settled_by_actor = ?, webhook_received_at = now(), " +
                    "webhook_signature_verified = ?, raw_webhook_payload = ?::jsonb " +
                    "WHERE qris_partner_reference_no = ? AND status = 'pending'",
            midtransTransactionId, settledByActor, signatureVerified, rawPayload, partnerReferenceNo)

    /**
     * A settlement for a charge already written off — `expired` by reconciliation, or
     * `failed` because cash was taken while its QR was on screen ([markWithdrawn]).
     * The money is real, so it is recorded; the caller decides whether it is owed back.
     */
    fun markPaidLate(c: Connection, partnerReferenceNo: String?, midtransTransactionId: String?,
                     settledByActor: String?, signatureVerified: Boolean, rawPayload: String?): Int =
        db.execute(c,
            "UPDATE payment SET status = 'paid', paid_at = now(), qris_reference_no = ?, " +
                    "settled_by_actor = ?, webhook_received_at = now(), " +
                    "webhook_signature_verified = ?, raw_webhook_payload = ?::jsonb " +
                    "WHERE qris_partner_reference_no = ? AND status IN ('expired', 'failed')",
            midtransTransactionId, settledByActor, signatureVerified, rawPayload, partnerReferenceNo)

    /**
     * Withdraws a pending QRIS charge because the order was just paid in cash. Like
     * [markGivenUp], it stamps no webhook columns: no webhook arrived. `failed`
     * rather than `expired` because it is what Midtrans's own `cancel` maps to.
     * `status = 'pending'` is the race guard: a settlement already applied wins.
     */
    fun markWithdrawn(c: Connection, tenantId: UUID?, paymentId: UUID?): Int =
        db.execute(c,
            "UPDATE payment SET status = 'failed' " +
                    "WHERE tenant_id = ? AND payment_id = ? AND status = 'pending'",
            tenantId, paymentId)

    fun markTerminalStatus(c: Connection, partnerReferenceNo: String?, status: String?,
                           signatureVerified: Boolean, rawPayload: String?): Int =
        db.execute(c,
            "UPDATE payment SET status = ?, webhook_received_at = now(), " +
                    "webhook_signature_verified = ?, raw_webhook_payload = ?::jsonb " +
                    "WHERE qris_partner_reference_no = ? AND status = 'pending'",
            status, signatureVerified, rawPayload, partnerReferenceNo)

    /**
     * Gives up on a pending payment Midtrans has confirmed cannot settle, moving it
     * `pending → expired`. The counterpart to `ReservationLifecycleService`'s
     * `held → expired` for holds, and the transition whose absence left the reconciliation
     * scan re-querying dead rows forever.
     *
     * Deliberately **not** [markTerminalStatus], though the status written is the
     * same: that method stamps `webhook_received_at = now()` and the signature/payload
     * columns, and no webhook arrived here. Recording one would forge the evidence trail that
     * the audit relies on — a row claiming Midtrans told us something when what actually happened is
     * that we stopped asking.
     *
     * `status = 'pending'` in the WHERE is the race guard, not decoration: a real
     * settlement landing between the decision and this UPDATE must win, and it does, because it
     * moves the row off `pending` first and this statement then matches nothing.
     */
    fun markGivenUp(c: Connection, tenantId: UUID?, paymentId: UUID?): Int =
        db.execute(c,
            "UPDATE payment SET status = 'expired', last_reconciled_at = now() " +
                    "WHERE tenant_id = ? AND payment_id = ? AND status = 'pending'",
            tenantId, paymentId)

    /** The reconciliation scan: QRIS charges still pending, oldest first, so a
     * capped batch always makes progress on the longest-outstanding rather than revisiting
     * the newest. Cash never appears — it is settled at the moment it is taken. */
    fun findPendingForReconciliation(c: Connection, tenantId: UUID?, limit: Int): List<Payment> =
        db.query(c,
            "SELECT " + COLUMNS + " FROM payment " +
                    "WHERE tenant_id = ? AND status = 'pending' AND payment_channel = 'qris' " +
                    "ORDER BY created_at LIMIT " + limit,
            ::map, tenantId)

    /**
     * Adds one cancelled seat's price to what this payment owes back.
     *
     * Guarded on `status = 'paid'` — only money actually taken can be owed back. A
     * pending charge that is cancelled owes nothing (it expires on its own), and re-running
     * this against a non-paid row is a no-op rather than an error, which is what lets the
     * caller ask unconditionally.
     *
     * Accumulates with `+ ?` rather than assigning, because seats in a group are
     * cancelled one at a time. `refund_due_at` uses COALESCE so it records when the debt
     * first arose and does not creep forward with each additional seat; the reason is kept for
     * the same purpose, first-writer-wins, since the earliest cancellation is the one that
     * explains why money is owed.
     *
     * The return value tells the caller whether an obligation was actually recorded, which
     * is what `BookingService` logs — a cancellation that silently failed to record a
     * debt is the original bug.
     */
    fun recordRefundDue(c: Connection, tenantId: UUID?, paymentId: UUID?,
                        additionalAmount: BigDecimal?, reason: String?): Int =
        db.execute(c,
            "UPDATE payment SET refund_due_amount = refund_due_amount + ?, " +
                    "refund_due_at = COALESCE(refund_due_at, now()), " +
                    "refund_reason = COALESCE(refund_reason, ?) " +
                    "WHERE tenant_id = ? AND payment_id = ? AND status = 'paid'",
            additionalAmount, reason, tenantId, paymentId)

    /**
     * Applies a gateway refund (BI-SNAP `'04'`): sets the debt to [remaining], and appends the
     * notification to `raw_webhook_payload` under `_gatewayRefunds` rather than replacing it, so
     * the settlement's own payload stays. [flag], when not null, is what staff must look at, and
     * is what [findGatewayRefundsFlagged] lists. [applied] is a JSON array of the refunds this
     * notification counted (`RefundLedger`), appended under `_refundsApplied`: that list, not the
     * body, is what stops one refund clearing a debt twice. Returns 0 for a body already appended,
     * Midtrans's plain redelivery, which then changes nothing at all.
     */
    fun recordGatewayRefund(c: Connection, tenantId: UUID?, paymentId: UUID?, remaining: BigDecimal,
                            rawBody: String?, flag: String?, applied: String): Int =
        db.execute(c,
            "UPDATE payment SET refund_due_amount = ?, " +
                    // V1's CHECK: the stamp goes with the debt, and with it.
                    "refund_due_at = CASE WHEN ? > 0 THEN refund_due_at END, " +
                    "raw_webhook_payload = COALESCE(raw_webhook_payload, '{}'::jsonb) " +
                    "|| jsonb_build_object('_gatewayRefunds', " +
                    "COALESCE(raw_webhook_payload -> '_gatewayRefunds', '[]'::jsonb) || jsonb_build_array(?::jsonb)) " +
                    "|| jsonb_build_object('_refundsApplied', " +
                    "COALESCE(raw_webhook_payload -> '_refundsApplied', '[]'::jsonb) || ?::jsonb) " +
                    // A new flag nulls a resolution staff recorded for an earlier one, so the row is
                    // listed again: a second refund is a second thing to judge.
                    "|| CASE WHEN CAST(? AS text) IS NULL THEN '{}'::jsonb " +
                    "ELSE jsonb_build_object('_gatewayRefundFlag', CAST(? AS text), " +
                    "'_gatewayRefundResolvedAt', NULL, '_gatewayRefundResolvedBy', NULL) END " +
                    "WHERE tenant_id = ? AND payment_id = ? " +
                    "AND NOT COALESCE(raw_webhook_payload -> '_gatewayRefunds', '[]'::jsonb) @> jsonb_build_array(?::jsonb)",
            remaining, remaining, rawBody, applied, flag, flag, tenantId, paymentId, rawBody)

    fun findByIdForUpdate(c: Connection, tenantId: UUID?, paymentId: UUID?): Optional<Payment> =
        db.queryOne(c, "SELECT " + COLUMNS + " FROM payment WHERE tenant_id = ? AND payment_id = ? FOR UPDATE",
            ::map, tenantId, paymentId)

    /**
     * `RefundService`'s one write: the debt now ([remaining]), refunds counted ([applied], a JSON
     * array appended under `_refundsApplied`, as [recordGatewayRefund] appends), its own state
     * under `_autoRefund`, and a [flag] for staff when not null, which re-lists a resolved row as a
     * new `'04'` flag does. The caller holds the row's `FOR UPDATE`.
     */
    fun updateRefundState(c: Connection, tenantId: UUID?, paymentId: UUID, remaining: BigDecimal,
                          applied: String, autoRefund: String, flag: String?): Int =
        db.execute(c,
            "UPDATE payment SET refund_due_amount = ?, " +
                    "refund_due_at = CASE WHEN ? > 0 THEN refund_due_at END, " +
                    "raw_webhook_payload = COALESCE(raw_webhook_payload, '{}'::jsonb) " +
                    "|| jsonb_build_object('_autoRefund', ?::jsonb, '_refundsApplied', " +
                    "COALESCE(raw_webhook_payload -> '_refundsApplied', '[]'::jsonb) || ?::jsonb) " +
                    "|| CASE WHEN CAST(? AS text) IS NULL THEN '{}'::jsonb " +
                    "ELSE jsonb_build_object('_gatewayRefundFlag', CAST(? AS text), " +
                    "'_gatewayRefundResolvedAt', NULL, '_gatewayRefundResolvedBy', NULL) END " +
                    "WHERE tenant_id = ? AND payment_id = ?",
            remaining, remaining, autoRefund, applied, flag, flag, tenantId, paymentId)

    /** Payments whose automatic refund started, is not refused, and still owes: the sweep's list. */
    fun findAutoRefundsOpen(c: Connection, tenantId: UUID?, limit: Int): List<UUID> =
        db.query(c,
            "SELECT payment_id FROM payment WHERE tenant_id = ? AND status = 'paid' AND refund_due_amount > 0 " +
                    "AND raw_webhook_payload -> '_autoRefund' IS NOT NULL AND raw_webhook_payload -> '_autoRefund' ->> 'refused' IS NULL " +
                    "ORDER BY refund_due_at LIMIT " + limit,
            { rs -> rs.getObject(1, UUID::class.java) }, tenantId)

    /** Gateway refunds staff must judge and have not marked resolved, newest first. The flag is read
     * back into [Payment.refundReason] for the page, since the debt's own reason is beside the point
     * once the gateway has paid. */
    fun findGatewayRefundsFlagged(c: Connection, tenantId: UUID?, limit: Int): List<Payment> =
        db.query(c,
            "SELECT " + COLUMNS.replace("refund_reason", "raw_webhook_payload ->> '_gatewayRefundFlag' AS refund_reason") +
                    " FROM payment WHERE tenant_id = ? AND raw_webhook_payload ->> '_gatewayRefundFlag' IS NOT NULL " +
                    "AND raw_webhook_payload ->> '_gatewayRefundResolvedAt' IS NULL " +
                    "ORDER BY webhook_received_at DESC NULLS LAST LIMIT " + limit,
            ::map, tenantId)

    /**
     * Staff's "Mark resolved" on a flagged gateway refund: stamps when and by whom (an app_user id) beside the flag,
     * which stays, so the row leaves the queue and the record of what was judged does not. A key in
     * `raw_webhook_payload`, as the flag is, so no migration. Only a flagged row takes the stamp.
     */
    fun resolveGatewayRefundFlag(c: Connection, tenantId: UUID?, paymentId: UUID?, resolvedBy: String?): Int =
        db.execute(c,
            "UPDATE payment SET raw_webhook_payload = raw_webhook_payload || " +
                    "jsonb_build_object('_gatewayRefundResolvedAt', now(), '_gatewayRefundResolvedBy', CAST(? AS text)) " +
                    "WHERE tenant_id = ? AND payment_id = ? AND raw_webhook_payload ->> '_gatewayRefundFlag' IS NOT NULL",
            resolvedBy, tenantId, paymentId)

    /** One line of [salesByDay]: a hall's local day, its branch (or the hall, if unassigned), one channel. */
    data class SalesLine(val day: LocalDate, val cinema: String, val city: String?, val channel: String,
                         val payments: Int, val gross: BigDecimal, val refundOwed: BigDecimal)

    /**
     * Paid payments by the hall's local date of `paid_at`, branch and channel: the sales report
     * (`/admin/payments/sales.csv`). Gross and what is still owed back are summed side by side, never
     * netted: the platform moves no money back, so "net" would be a guess about refunds staff made by
     * hand. City is there because PBJT is a kabupaten/kota tax, so a chain files per city.
     * `resource_pool.timezone`, not the site's, because the hall's is the override (`Site.timezone`).
     */
    fun salesByDay(c: Connection, tenantId: UUID?, from: LocalDate, to: LocalDate): List<SalesLine> =
        db.query(c,
            "SELECT (p.paid_at AT TIME ZONE rp.timezone)::date AS day, COALESCE(s.name, rp.name) AS cinema, " +
                    "s.city, p.payment_channel, count(*) AS payments, sum(p.amount) AS gross, " +
                    "sum(p.refund_due_amount) AS refund_owed " +
                    "FROM payment p " +
                    "JOIN reservation_group g ON g.reservation_group_id = p.reservation_group_id " +
                    "JOIN resource_pool rp ON rp.resource_pool_id = g.resource_pool_id " +
                    "LEFT JOIN site s ON s.site_id = rp.site_id " +
                    "WHERE p.tenant_id = ? AND p.status = 'paid' " +
                    "AND (p.paid_at AT TIME ZONE rp.timezone)::date BETWEEN ? AND ? " +
                    "GROUP BY 1, s.site_id, rp.resource_pool_id, 2, 3, 4 ORDER BY 1, 2, 4",
            { rs -> SalesLine(rs.getObject("day", LocalDate::class.java), rs.getString("cinema"),
                rs.getString("city"), rs.getString("payment_channel"), rs.getInt("payments"),
                rs.getBigDecimal("gross"), rs.getBigDecimal("refund_owed")) },
            tenantId, from, to)

    /** Settled payments still owing money back, oldest debt first — the query the partial index
     * on refunds due exists for, and half of what `/admin/payments` lists. The WHERE and the ORDER BY
     * mirror that index deliberately: loosening either silently drops it. */
    fun findRefundsDue(c: Connection, tenantId: UUID?, limit: Int): List<Payment> =
        db.query(c,
            "SELECT " + COLUMNS + " FROM payment " +
                    "WHERE tenant_id = ? AND refund_due_amount > 0 " +
                    "ORDER BY refund_due_at LIMIT " + limit,
            ::map, tenantId)

    /**
     * Stamps a payment as awaiting a manual fraud decision, leaving its status alone.
     *
     * `COALESCE` so the first stamp wins, for the reason `refund_due_at` uses it:
     * the reconciliation scan re-reads `capture+challenge` every run, and a stamp that crept
     * forward each time would make every open review read as "just now" — destroying the one thing
     * the column exists to answer, which is how long a human has been sitting on this.
     *
     * Deliberately does **not** touch `webhook_received_at`, `webhook_signature_verified` or
     * `raw_webhook_payload`, though the caller has all three
     * on the webhook path. Reconciliation reaches this same branch with no webhook at all, and
     * writing those there would forge the evidence trail — the same rule
     * [markGivenUp] states for the status it writes.
     *
     * Guarded on `status = 'pending'` like every other write here: a decision that landed
     * first must win, and this must not re-open a row that has already settled or failed.
     */
    fun markUnderFraudReview(c: Connection, partnerReferenceNo: String?): Int =
        db.execute(c,
            "UPDATE payment SET fraud_review_at = COALESCE(fraud_review_at, now()) " +
                    "WHERE qris_partner_reference_no = ? AND status = 'pending'",
            partnerReferenceNo)

    /** Captured payments awaiting a manual fraud decision, longest-waiting first — the query the
     * partial fraud-review index exists for, and what `/admin/payments` lists. Terminal rows drop
     * out on their own: an accepted review moves the row to `paid` and a denied one to
     * `failed`, so nothing has to clear the stamp. */
    fun findUnderFraudReview(c: Connection, tenantId: UUID?, limit: Int): List<Payment> =
        db.query(c,
            "SELECT " + COLUMNS + " FROM payment " +
                    "WHERE tenant_id = ? AND fraud_review_at IS NOT NULL AND status = 'pending' " +
                    "ORDER BY fraud_review_at LIMIT " + limit,
            ::map, tenantId)

    fun touchReconciled(c: Connection, tenantId: UUID?, paymentId: UUID?): Int =
        db.execute(c,
            "UPDATE payment SET last_reconciled_at = now() WHERE tenant_id = ? AND payment_id = ?",
            tenantId, paymentId)

    private fun map(rs: ResultSet): Payment {
        val paidAt = rs.getTimestamp("paid_at")
        val webhookAt = rs.getTimestamp("webhook_received_at")
        val reconciledAt = rs.getTimestamp("last_reconciled_at")
        val refundDueAt = rs.getTimestamp("refund_due_at")
        val fraudReviewAt = rs.getTimestamp("fraud_review_at")
        return Payment(
            rs.getObject("payment_id", UUID::class.java),
            rs.getObject("tenant_id", UUID::class.java),
            rs.getObject("reservation_group_id", UUID::class.java),
            rs.getBigDecimal("amount"),
            rs.getString("currency"),
            rs.getString("qris_merchant_id"),
            rs.getString("qris_terminal_id"),
            rs.getString("qris_partner_reference_no"),
            rs.getString("qris_content"),
            rs.getString("qris_reference_no"),
            rs.getString("status"),
            rs.getTimestamp("expires_at").toInstant(),
            paidAt?.toInstant(),
            webhookAt?.toInstant(),
            rs.getBoolean("webhook_signature_verified"),
            rs.getString("raw_webhook_payload"),
            rs.getString("payment_channel"),
            rs.getString("trigger_point"),
            rs.getString("settled_by_actor"),
            reconciledAt?.toInstant(),
            fraudReviewAt?.toInstant(),
            rs.getBigDecimal("refund_due_amount"),
            refundDueAt?.toInstant(),
            rs.getString("refund_reason"),
            rs.getTimestamp("created_at").toInstant(),
        )
    }

    companion object {
        private const val COLUMNS =
            "payment_id, tenant_id, reservation_group_id, amount, currency, qris_merchant_id, " +
                    "qris_terminal_id, qris_partner_reference_no, qris_content, qris_reference_no, " +
                    "status, expires_at, paid_at, webhook_received_at, webhook_signature_verified, " +
                    "raw_webhook_payload::text AS raw_webhook_payload, payment_channel, trigger_point, " +
                    "settled_by_actor, last_reconciled_at, fraud_review_at, refund_due_amount, " +
                    "refund_due_at, refund_reason, created_at"

        /** The partial unique index: one paid cash payment per order. Matched by name, like
         * `ReservationGroupRepository`'s booking-code index, because 23505 alone does not say
         * which unique index refused the row. */
        private const val ONE_CASH_PER_ORDER_INDEX = "idx_payment_one_cash_per_order"

        /** True when `e` is `idx_payment_one_cash_per_order` refusing a second paid cash row for an order. Static, as it was
         * in Java, so `PaymentRepository.isSecondCashPayment(e)` still compiles in the tests. */
        @JvmStatic
        fun isSecondCashPayment(e: DataAccessException): Boolean =
            e.isUniqueViolation() && e.message != null &&
                    e.message!!.contains(ONE_CASH_PER_ORDER_INDEX)
    }
}
